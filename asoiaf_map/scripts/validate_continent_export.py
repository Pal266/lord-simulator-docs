"""
Checks of the continental engine layers (export_continent.py) against the continental model.

  * seams    - neighbouring tiles have identical heights and classes on their shared edges;
  * fidelity - decoded heights equal the continental surface within the encoding step; every land cell of the model
               lies in an exported tile; surface classes agree with the model's masks;
  * water    - river water surfaces never rise downstream; rivers run on land; lake outlines are valid polygons whose
               areas match the model's lakes.

Usage:  python validate_continent_export.py
Writes ../output/VALIDATION_CONTINENT_EXPORT.md and ../output/validation_continent_export.json; exits with code 1 if
any check fails.
"""
import json, os, sys
import numpy as np
from PIL import Image
from scipy import ndimage
from shapely.geometry import Polygon
import frame

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "output")
EXPORT = os.path.join(HERE, "..", "export", "continent")
checks = []


def check(kind, name, value, lo, hi, unit="", note=""):
    checks.append(dict(kind=kind, name=name, value=value if isinstance(value, bool) else round(float(value), 4), band=[lo, hi],
                       unit=unit, passed=bool(lo <= value <= hi), note=note))


man = json.load(open(os.path.join(EXPORT, "manifest.json")))
enc = man["layers"][0]["encoding"].split()
off, step = float(enc[2]), float(enc[6])
C = np.load(os.path.join(OUT, "continent.npz"))
xs, ys = C["x_m"].astype(np.float64), C["y_m"].astype(np.float64); dx = float(C["dx_m"])
z = C["elevation_m"]; land = C["land"]; lake = C["lake"]; H, W = z.shape
T = man["tiles"]; nv = T["vertices"]; sp = T["vertex_spacing_m"]
tiles = {(t["I"], t["J"]): t for t in T["list"]}

# ---------------- seams and fidelity ----------------
hts, cls = {}, {}
for k, t in tiles.items():
    hts[k] = off + np.array(Image.open(os.path.join(EXPORT, t["name"], "heightmap.png"))).astype(np.float64) * step
    cls[k] = np.array(Image.open(os.path.join(EXPORT, t["name"], "surface.png")))
seam_h = seam_c = 0.0; nseam = 0
for (I, J) in tiles:
    for nb, a, b in (((I + 1, J), (slice(None), -1), (slice(None), 0)), ((I, J + 1), (-1, slice(None)), (0, slice(None)))):
        if nb in tiles:
            seam_h = max(seam_h, float(np.abs(hts[(I, J)][a] - hts[nb][b]).max()))
            seam_c = max(seam_c, float((cls[(I, J)][a] != cls[nb][b]).mean())); nseam += 1
check("seams", "Largest height difference on shared tile edges", seam_h, 0, 0, "m", f"{nseam} shared edges")
check("seams", "Share of differing surface classes on shared tile edges", 100 * seam_c, 0, 0, "%")

err = 0.0; agree = []; covered = np.zeros((H, W), bool)
off_v = np.arange(nv) * sp
for k, t in tiles.items():
    x0, y0 = t["nw_continental_m"]
    X, Y = np.meshgrid(x0 + off_v, y0 - off_v)
    r = (ys[0] - Y) / dx; c = (X - xs[0]) / dx
    zc = ndimage.map_coordinates(z, [r, c], order=1, mode="nearest")
    err = max(err, float(np.abs(hts[k] - zc).max()))
    ri = np.clip(np.round(r).astype(int), 0, H - 1); ci = np.clip(np.round(c).astype(int), 0, W - 1)
    agree.append(float(((cls[k] != 0) == land[ri, ci]).mean()))
    covered[ri.min():ri.max() + 1, ci.min():ci.max() + 1] = True
check("fidelity", "Largest |decoded height - continental surface|", err, 0, step / 2 + 0.01, "m", f"encoding step {step} m; + 1 cm for float32 and mm-rounded tile corners")
check("fidelity", "Share of the model's land cells inside an exported tile", 100 * float(covered[land].mean()), 100, 100, "%")
check("fidelity", "Surface class sea / not sea agrees with the model's land mask", 100 * float(np.mean(agree)), 100, 100, "%")

# ---------------- water ----------------
wj = json.load(open(os.path.join(EXPORT, "water.json")))
rise = steps = 0; on_land = []
for rv in wj["rivers"]:
    p = np.array(rv["points_m"])
    d = np.diff(p[:, 2]); rise += int((d > 1e-6).sum()); steps += d.size
    r = np.round((ys[0] - p[:-1, 1]) / dx).astype(int); c = np.round((p[:-1, 0] - xs[0]) / dx).astype(int)
    on_land.append(land[r, c])
check("water", "River water surfaces rising downstream (steps)", rise, 0, 0, "", f"{steps} steps, {len(wj['rivers'])} river lines")
check("water", "River points (upstream of the mouth) on land", 100 * float(np.concatenate(on_land).mean()), 100, 100, "%")
bad = sum(not Polygon(l["outline_m"]).is_valid for l in wj["lakes"])
check("water", "Lake outlines that are not valid simple polygons", bad, 0, 0, "", f"{len(wj['lakes'])} lakes")
a_out = sum(Polygon(l["outline_m"]).area for l in wj["lakes"]) / 1e6
a_mod = sum(l["area_km2"] for l in wj["lakes"])
check("water", "Total outline area / model lake area (exported lakes)", a_out / a_mod, 0.9, 1.1)

passed = sum(c["passed"] for c in checks)
lines = ["# Validation of the continental engine layers", "", "Generated by `scripts/validate_continent_export.py`.", "",
         f"{len(tiles)} tiles of {nv} x {nv} vertices at {sp:.0f} m. **Result: {passed} / {len(checks)} checks passed.**", "",
         "| Kind | Check | Value | Accepted band | Result |", "|---|---|---|---|---|"]
for c in checks:
    u = f" {c['unit']}" if c["unit"] else ""; note = f" ({c['note']})" if c["note"] else ""
    lines.append(f"| {c['kind']} | {c['name']}{note} | {c['value']}{u} | {c['band'][0]}–{c['band'][1]}{u} | {'PASS' if c['passed'] else 'FAIL'} |")
open(os.path.join(OUT, "VALIDATION_CONTINENT_EXPORT.md"), "w").write("\n".join(lines) + "\n")
json.dump(dict(passed=passed, total=len(checks), checks=checks), open(os.path.join(OUT, "validation_continent_export.json"), "w"), indent=1)
for c in checks:
    print(("PASS " if c["passed"] else "FAIL ") + f"[{c['kind']}] {c['name']}: {c['value']} (band {c['band']}) {c['note']}")
print(f"{passed}/{len(checks)} passed")
sys.exit(0 if passed == len(checks) else 1)
